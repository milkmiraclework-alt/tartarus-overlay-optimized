/* Supplemental references from explicitly labeled local screenshots.
 * node tools/panel-learn.js manifest.json [--check]
 * manifest: [{file: "...webp", tools: ["crown"]}]. Uses the isolated Electron
 * check for exactly the same image decoding as the real reader. Images stay
 * local; only compact visual features and names enter the repository.
 */
'use strict';
const fs = require('node:fs'), path = require('node:path');
const ROOT = path.resolve(__dirname, '..');
function readSamples(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8').replace(/^\uFEFF/, '')).map((row) => ({
    tools: row.tools, name: path.basename(row.file),
    url: 'data:image/' + (path.extname(row.file).toLowerCase() === '.webp' ? 'webp' : 'png') + ';base64,' + fs.readFileSync(row.file).toString('base64'),
  }));
}
async function browserPanels(labels, check) {
  for (const file of ['scan.js', 'scan-data.js', 'pick-data.js']) await new Promise((resolve, reject) => {
    const script = document.createElement('script'); script.src = 'js/' + file; script.onload = resolve; script.onerror = reject; document.head.appendChild(script);
  });
  const S = window.TartarusScan, ref = S.withPanelIcons(window.TARTARUS_SCAN, window.TARTARUS_PICK);
  const names = {}, icons = [], results = [];
  for (const label of labels) {
    if (!Array.isArray(label.tools) || label.tools.some((id) => !window.Tartarus.TOOLS[id])) throw new Error('Invalid instrument labels');
    const bitmap = await createImageBitmap(await (await fetch(label.url)).blob());
    const canvas = new OffscreenCanvas(bitmap.width, bitmap.height), ctx = canvas.getContext('2d', { willReadFrequently: true });
    ctx.drawImage(bitmap, 0, 0); bitmap.close();
    const img = ctx.getImageData(0, 0, canvas.width, canvas.height), loc = S.locateBoard(img, S.grayOf(img), ref);
    if (!loc || loc.score < 0.8) throw new Error('No confident prison layout: ' + label.name);
    const panel = S.readTools(img, loc, ref);
    const actual = panel.tools.map((t) => ({ sim: ref.toolNames[t.id]?.sim || t.id, conf: t.conf, score: t.score, margin: t.margin }));
    results.push({ image: label.name, expected: label.tools, actual });
    if (panel.tools.length !== label.tools.length) throw new Error('Detected/labeled icon counts disagree: ' + label.name);
    if (check) {
      if (actual.some((t, i) => t.sim !== label.tools[i])) throw new Error('Held-out icon misrecognized: ' + JSON.stringify(results.at(-1)));
      continue;
    }
    panel.tools.forEach((icon, i) => {
      const sim = label.tools[i], feat = S.artFeature(img, ...icon.box);
      const id = Object.keys(ref.toolNames).find((id) => ref.toolNames[id].sim === sim) || sim;
      names[id] = { sim, name: window.Tartarus.toolName(sim) };
      icons.push({ id, from: 'confirmed-panel', w: Math.round(icon.box[2] - icon.box[0]),
        feat: { grid: feat.grid.map((v) => Math.round(v * 10) / 10), hist: feat.hist.map((v) => Math.round(v * 1000) / 1000) } });
    });
  }
  return { names, icons, results };
}
function save(samples) {
  const file = path.join(ROOT, 'tools/panel-samples.json');
  const previous = fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : { names: {}, icons: [] };
  const extra = { names: { ...previous.names, ...samples.names }, icons: [...new Map(previous.icons.concat(samples.icons).map((icon) => [JSON.stringify(icon), icon])).values()] };
  fs.writeFileSync(file, JSON.stringify(extra, null, 2) + '\n');
  const pick = require('../js/pick-data.js');
  const output = { ...pick, names: extra.names, icons: pick.icons.filter((icon) => icon.from !== 'confirmed-panel').concat(extra.icons) };
  fs.writeFileSync(path.join(ROOT, 'js/pick-data.js'), `/* Generated by tools/pick-build.js; supplemental references from tools/panel-learn.js. */\n(function (root) {\n  root.TARTARUS_PICK = ${JSON.stringify(output)};\n  if (typeof module === 'object' && module.exports) module.exports = root.TARTARUS_PICK;\n})(typeof window !== 'undefined' ? window : typeof self !== 'undefined' ? self : globalThis);\n`);
}
module.exports = { readSamples, browserPanels, save };
if (require.main === module) {
  const manifest = process.argv[2];
  if (!manifest) throw new Error('Pass an explicit labeled-image manifest');
  const result = require('node:child_process').spawnSync(process.execPath, [path.join(__dirname, 'overlay-check.js'), '--panel-manifest', path.resolve(manifest), ...(process.argv.includes('--check') ? ['--check-panels'] : [])], { stdio: 'inherit', windowsHide: true });
  if (result.error) throw result.error;
  process.exitCode = result.status === null ? 1 : result.status;
}
